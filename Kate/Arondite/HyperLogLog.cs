/* HyperLogLog — это вероятностный алгоритм, который позволяет оценить количество уникальных элементов 
в большом потоке данных с использованием фиксированного объема памяти. Он не дает точного результата, 
но позволяет получать приближенное значение с высокой точностью при значительно меньших затратах памяти.

Представление данных: HyperLogLog работает путем хеширования каждого объекта в потоке данных и использования 
этого хеш-значения для оценки числа уникальных объектов.
Использование битов для хранения состояния: Вместо того чтобы хранить каждый объект, мы используем несколько битов 
(обычно порядка 12-16 бит), чтобы отслеживать поведение хеш-функции.
Генерация хешей: Каждый объект хешируется в строку битов, и далее анализируется, сколько ведущих нулей в этой строке. 
Например, если хеш объекта равен "00011010", то ведущее количество нулей — это 3.
Использование регистра: Для каждого хешированного объекта обновляется регистр, который хранит максимальное количество 
ведущих нулей для данного потока.
Оценка уникальных значений: Когда все объекты обработаны, HyperLogLog использует информацию о количестве ведущих нулей 
для всех хешей, чтобы приблизительно оценить количество уникальных элементов в потоке.

Алгоритм HyperLogLog:
Для каждого элемента из потока данных вычисляем хеш.
Определяем количество ведущих нулей в хеше.
Обновляем регистр для каждого бита, соответствующего количеству ведущих нулей.
После обработки всех данных вычисляем среднее значение регистров и используем формулу для получения оценки количества 
уникальных элементов.
*/

//Алгоритм HyperLogLog использует массив для хранения регистра и хеш-функцию для вычисления значений. Пример реализации на C#:
using System;
using System.Collections.Generic;

class HyperLogLog
{
  private int[] registers;  // Регистр для хранения максимального количества ведущих нулей
  private int b;  // Размер регистра (количество бит)
  private int m;  // Количество регистров (2^b)

  // Конструктор HyperLogLog
  public HyperLogLog(int b)
  {
    this.b = b;
    this.m = (int)Math.Pow(2, b);  // m = 2^b
    this.registers = new int[m];
  }

  // Хеш-функция (простая, для примера, на практике лучше использовать что-то более стойкое)
  private int Hash(string input)
  {
    return input.GetHashCode();
  }

  // Функция для добавления элемента в поток
  public void Add(string item)
  {
    int hashValue = Hash(item);
    int registerIndex = hashValue & (m - 1);  // Индекс регистра (модуляция по m)
    int leadingZeros = CountLeadingZeros(hashValue);  // Количество ведущих нулей в хеше
    registers[registerIndex] = Math.Max(registers[registerIndex], leadingZeros);
  }

  // Функция для подсчета ведущих нулей в хеше
  private int CountLeadingZeros(int hashValue)
  {
    int count = 0;
    while ((hashValue & (1 << (31 - count))) == 0 && count < 32)
    {
      count++;
    }
    return count;
  }

  // Оценка количества уникальных элементов
  public int Estimate()
  {
    // Вычисление среднего значения
    double sum = 0.0;
    foreach (var register in registers)
    {
      sum += Math.Pow(2, -register);
    }

    // Формула для оценки количества уникальных элементов
    double alphaMM = 0.7213 / (1 + 1.079 / m);  // Константа для улучшения точности
    double estimate = alphaMM * m * m / sum;
    return (int)estimate;
  }
}

class Program
{
  static void Main()
  {
    // Создаем объект HyperLogLog с размером регистра 12 бит (2^12 = 4096 регистров)
    HyperLogLog hll = new HyperLogLog(12);

    // Добавляем элементы в поток
    List<string> items = new List<string> { "apple", "banana", "orange", "apple", "banana", "kiwi" };
    foreach (var item in items)
    {
      hll.Add(item);
    }

    // Оцениваем количество уникальных элементов
    int uniqueCount = hll.Estimate();
    Console.WriteLine($"Оценка количества уникальных элементов: {uniqueCount}");
  }
}


